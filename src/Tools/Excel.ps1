function Invoke-ExcelApplyColorScale {
    <#
    .SYNOPSIS
    Applies an Excel Color Scale (Heatmap) or Data Bars.

    .DESCRIPTION
    Adds visual conditional formatting to a specified column, helping to instantly identify high/low values through a red-yellow-green heatmap or blue data bars.

    .PARAMETER FilePath
    The absolute path to the Excel file.

    .PARAMETER SheetName
    Optional. The sheet to modify. Defaults to 'Sheet1'.

    .PARAMETER ColumnLetter
    The letter of the column to format (e.g., 'C').

    .PARAMETER Type
    The type of formatting. Valid options: 'Heatmap', 'DataBar'. Default is 'Heatmap'.

    .EXAMPLE
    Invoke-ExcelApplyColorScale -FilePath "C:\Data.xlsx" -ColumnLetter "D" -Type "Heatmap"
    Applies a color scale to column D.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$FilePath, 
        [string]$SheetName = "Sheet1", 
        [Parameter(Mandatory = $true)][string]$ColumnLetter,
        [ValidateSet("Heatmap", "DataBar")][string]$Type = "Heatmap"
    )
    Write-ToolLine "Excel" "Applying $Type" "Col $ColumnLetter in $FilePath"
    
    $excel = $null; $wb = $null; $ws = $null
    try {
        $excel = New-Object -ComObject Excel.Application
        $excel.Visible = $false
        $wb = $excel.Workbooks.Open($FilePath)
        $ws = try { $wb.Sheets.Item($SheetName) } catch { $wb.ActiveSheet }
        
        $lastRow = $ws.UsedRange.Rows.Count
        $range = $ws.Range("${ColumnLetter}2:${ColumnLetter}${lastRow}")
        $range.FormatConditions.Delete()
        
        if ($Type -eq "Heatmap") {
            $cs = $range.FormatConditions.AddColorScale(3)
            $cs.ColorScaleCriteria.Item(1).FormatColor.Color = 7039480   # Light Red
            $cs.ColorScaleCriteria.Item(2).FormatColor.Color = 8711167   # Yellow
            $cs.ColorScaleCriteria.Item(3).FormatColor.Color = 8125023   # Light Green
        }
        else {
            $db = $range.FormatConditions.AddDatabar()
            $db.BarColor.Color = 13012579 # Nice Blue
        }
        
        $wb.Save()
        Write-StatusLine "OK" "$Type applied to $ColumnLetter"
        return "Successfully applied $Type to column $ColumnLetter in $SheetName."
    }
    catch {
        return "ERROR: $_"
    }
    finally {
        if ($ws) { Dispose-ComObject $ws }
        if ($wb) { $wb.Close($false); Dispose-ComObject $wb }
        if ($excel) { $excel.Quit(); Dispose-ComObject $excel }
        [System.GC]::Collect(); [System.GC]::WaitForPendingFinalizers()
    }
}

