function Invoke-ExcelRemoveDuplicates {
    <#
    .SYNOPSIS
    Instantly removes duplicate rows based on specific columns.

    .DESCRIPTION
    Uses Excel's native RemoveDuplicates COM method to clean a dataset. You can specify exactly which columns should be checked for duplicate values.

    .PARAMETER FilePath
    The absolute path to the Excel file.

    .PARAMETER SheetName
    Optional. The sheet to clean. Defaults to 'Sheet1'.

    .PARAMETER ColumnsToCheck
    Optional. An array of column indices (1-based) to evaluate. If omitted, checks all columns.

    .EXAMPLE
    Invoke-ExcelRemoveDuplicates -FilePath "C:\Data.xlsx" -ColumnsToCheck @(1, 2)
    Removes rows where the combination of columns A and B are duplicates.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$FilePath, 
        [string]$SheetName = "Sheet1", 
        [int[]]$ColumnsToCheck
    )
    Write-ToolLine "Excel" "Removing Duplicates" $FilePath
    
    $excel = $null; $wb = $null; $ws = $null
    try {
        $excel = New-Object -ComObject Excel.Application
        $excel.Visible = $false
        $excel.DisplayAlerts = $false
        
        $wb = $excel.Workbooks.Open($FilePath)
        $ws = try { $wb.Sheets.Item($SheetName) } catch { $wb.ActiveSheet }
        
        $used = $ws.UsedRange
        $startRows = $used.Rows.Count
        
        if ($null -eq $ColumnsToCheck -or $ColumnsToCheck.Count -eq 0) {
            $ColumnsToCheck = 1..$used.Columns.Count
        }
        
        # COM Interop requires a very specific [Object[]] cast for arrays in RemoveDuplicates
        [Object[]]$SafeArray = $ColumnsToCheck 
        
        # 1 = xlYes (Has Headers)
        $used.RemoveDuplicates([ref]$SafeArray, 1)
        
        $endRows = $ws.UsedRange.Rows.Count
        $removed = $startRows - $endRows
        
        $wb.Save()
        Write-StatusLine "OK" "Removed $removed duplicates"
        return "Successfully removed $removed duplicate rows from $SheetName."
    }
    catch {
        return "ERROR: $_"
    }
    finally {
        if ($ws) { Dispose-ComObject $ws }
        if ($wb) { $wb.Close($false); Dispose-ComObject $wb }
        if ($excel) { $excel.Quit(); Dispose-ComObject $excel }
        [System.GC]::Collect(); [System.GC]::WaitForPendingFinalizers()
    }
}

