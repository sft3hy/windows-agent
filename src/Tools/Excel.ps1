function Invoke-ExcelGetMetadata {
    <#
    .SYNOPSIS
    Allows the LLM to instantly "see" the structure of the Excel file.

    .DESCRIPTION
    Quickly scans a workbook and returns a lightweight summary of all sheets, including their row counts, column counts, and column headers. This is much faster and safer than reading the entire file.

    .PARAMETER FilePath
    The absolute path to the Excel file.

    .EXAMPLE
    Invoke-ExcelGetMetadata -FilePath "C:\Report.xlsx"
    Returns a text summary of the sheets and their columns.
    #>
    param([Parameter(Mandatory = $true)][string]$FilePath)
    Write-ToolLine "Excel" "Getting Metadata" $FilePath
    
    $excel = $null; $wb = $null
    try {
        if (-not (Test-Path $FilePath)) { throw "File not found." }
        
        $excel = New-Object -ComObject Excel.Application
        $excel.Visible = $false
        $excel.DisplayAlerts = $false
        $wb = $excel.Workbooks.Open($FilePath, $null, $true) # Read-only
        
        $output = "Workbook: $($wb.Name)`n"
        foreach ($ws in $wb.Sheets) {
            $used = $ws.UsedRange
            $rows = $used.Rows.Count
            $cols = $used.Columns.Count
            
            $headers = @()
            if ($rows -gt 0 -and $cols -gt 0 -and $ws.Cells.Item(1, 1).Text -ne "") {
                # Read row 1 into an array much faster than cell-by-cell if possible, 
                # but cell-by-cell is safer for COM boundaries on row 1
                for ($c = 1; $c -le $cols; $c++) {
                    $val = $ws.Cells.Item(1, $c).Text
                    if (-not [string]::IsNullOrWhiteSpace($val)) { $headers += $val }
                }
            }
            $output += "- Sheet: '$($ws.Name)' | Rows: $rows | Cols: $cols`n"
            $output += "  Headers: $($headers -join ', ')`n"
            Dispose-ComObject $ws
        }
        
        Write-StatusLine "OK" "Metadata retrieved"
        return $output
    }
    catch {
        return "ERROR: $_"
    }
    finally {
        if ($wb) { $wb.Close($false); Dispose-ComObject $wb }
        if ($excel) { $excel.Quit(); Dispose-ComObject $excel }
        [System.GC]::Collect(); [System.GC]::WaitForPendingFinalizers()
    }
}

