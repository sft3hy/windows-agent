# ============================================================

function Invoke-ExcelRunSQL {
    <#
    .SYNOPSIS
    Runs actual SQL queries directly against the Excel file.

    .DESCRIPTION
    Uses the Microsoft ACE OLEDB engine to execute standard SQL commands (like SELECT, WHERE, GROUP BY) against the data in an Excel sheet. This is extremely fast for querying large datasets without opening the file in the Excel UI.

    .PARAMETER FilePath
    The absolute path to the Excel file.

    .PARAMETER SqlQuery
    The SQL query to execute. Sheet names must be enclosed in brackets with a trailing dollar sign, e.g., [Sheet1$].

    .EXAMPLE
    Invoke-ExcelRunSQL -FilePath "C:\Data.xlsx" -SqlQuery "SELECT * FROM [Sheet1$] WHERE Status = 'Open'"
    Returns all rows where the Status column is 'Open'.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$FilePath, 
        [Parameter(Mandatory = $true)][string]$SqlQuery
    )
    Write-ToolLine "Excel" "Running SQL Query" "$SqlQuery on $FilePath"
    
    try {
        if (-not (Test-Path $FilePath)) { throw "File not found." }
        
        $ext = [System.IO.Path]::GetExtension($FilePath).ToLower()
        $props = switch ($ext) {
            ".xls" { "Excel 8.0;HDR=YES;IMEX=1" }
            ".xlsb" { "Excel 12.0;HDR=YES;IMEX=1" }
            ".xlsm" { "Excel 12.0 Macro;HDR=YES;IMEX=1" }
            default { "Excel 12.0 Xml;HDR=YES;IMEX=1" } # .xlsx
        }
        
        $connString = "Provider=Microsoft.ACE.OLEDB.12.0;Data Source=$FilePath;Extended Properties=`"$props`";"
        
        $conn = New-Object System.Data.OleDb.OleDbConnection($connString)
        $conn.Open()
        
        $cmd = New-Object System.Data.OleDb.OleDbCommand($SqlQuery, $conn)
        $adapter = New-Object System.Data.OleDb.OleDbDataAdapter($cmd)
        $dataset = New-Object System.Data.DataSet
        [void]$adapter.Fill($dataset)
        $conn.Close()
        
        $table = $dataset.Tables[0]
        if ($table.Rows.Count -eq 0) { return "Query successful, but returned 0 rows." }

        # Output to CSV format for LLM reading
        $csvOutput = New-Object System.Text.StringBuilder
        $headers = $table.Columns | ForEach-Object { $_.ColumnName }
        [void]$csvOutput.AppendLine(($headers -join ","))
        
        foreach ($row in $table.Rows) {
            $rowItems = $row.ItemArray | ForEach-Object { 
                $val = $_.ToString()
                if ($val -match '[,"]') { "`"$($val -replace '"','""')`"" } else { $val }
            }
            [void]$csvOutput.AppendLine(($rowItems -join ","))
        }
        
        Write-StatusLine "OK" "SQL returned $($table.Rows.Count) rows"
        return $csvOutput.ToString()
    }
    catch {
        if ($_.Exception.Message -match "Microsoft.ACE.OLEDB") {
            return "ERROR: Microsoft Access Database Engine is not installed. Cannot run SQL on Excel. Install the ACE OLEDB 12.0/16.0 provider."
        }
        return "ERROR running SQL. Ensure Query uses Excel syntax (e.g., SELECT * FROM [Sheet1$]). Details: $_"
    }
}

