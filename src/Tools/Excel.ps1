function Invoke-ExcelAddChart {
    <#
    .SYNOPSIS
    Generates visually appealing embedded charts natively in Excel.

    .DESCRIPTION
    Creates a new embedded chart (Bar, Line, or Pie) based on a specified data range and places it next to the data in the worksheet.

    .PARAMETER FilePath
    The absolute path to the Excel file.

    .PARAMETER DataRange
    The range of cells to chart (e.g., 'A1:B10'). Ensure it includes headers.

    .PARAMETER SheetName
    Optional. The sheet containing the data. Defaults to 'Sheet1'.

    .PARAMETER ChartType
    Optional. The type of chart to generate: 'Bar', 'Line', 'Pie'. Default is 'Bar'.

    .PARAMETER ChartTitle
    Optional. The title to display above the chart.

    .EXAMPLE
    Invoke-ExcelAddChart -FilePath "C:\Data.xlsx" -DataRange "A1:B5" -ChartType "Pie" -ChartTitle "Sales Dist"
    Creates a Pie chart for the data in A1:B5.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$FilePath,
        [Parameter(Mandatory = $true)][string]$DataRange, # e.g., "A1:B10"
        [string]$SheetName = "Sheet1",
        [ValidateSet("Bar", "Line", "Pie")][string]$ChartType = "Bar",
        [string]$ChartTitle = "Data Chart"
    )
    Write-ToolLine "Excel" "Creating $ChartType Chart" $FilePath
    
    $excel = $null; $wb = $null; $ws = $null
    try {
        $excel = New-Object -ComObject Excel.Application
        $excel.Visible = $false
        $wb = $excel.Workbooks.Open($FilePath)
        $ws = try { $wb.Sheets.Item($SheetName) } catch { $wb.ActiveSheet }
        
        $range = $ws.Range($DataRange)
        
        # AddChart2(Style, XlChartType, Left, Top, Width, Height)
        $xlChartType = switch ($ChartType) {
            "Bar" { 51 } # xlColumnClustered
            "Line" { 4 }  # xlLine
            "Pie" { 5 }  # xlPie
        }
        
        # Position chart 2 columns to the right of the data
        $leftPos = $range.Left + $range.Width + 20
        $topPos = $range.Top
        
        $chartObj = $ws.Shapes.AddChart2(251, $xlChartType, $leftPos, $topPos, 350, 250)
        $chart = $chartObj.Chart
        $chart.SetSourceData($range)
        $chart.HasTitle = $true
        $chart.ChartTitle.Text = $ChartTitle
        
        $wb.Save()
        Write-StatusLine "OK" "Chart generated"
        return "Successfully created $ChartType chart titled '$ChartTitle' using range $DataRange."
    }
    catch {
        return "ERROR: $_"
    }
    finally {
        if ($ws) { Dispose-ComObject $ws }
        if ($wb) { $wb.Close($false); Dispose-ComObject $wb }
        if ($excel) { $excel.Quit(); Dispose-ComObject $excel }
        [System.GC]::Collect(); [System.GC]::WaitForPendingFinalizers()
    }
}

