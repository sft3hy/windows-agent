    Converts an Excel analysis into a polished PDF report.

    .DESCRIPTION
    Exports either a specific worksheet or the entire workbook into a PDF file. Automatically configures page setup (landscape, fit to 1 page wide) for optimal viewing.

    .PARAMETER FilePath
    The absolute path to the source Excel file.

    .PARAMETER PdfPath
    The absolute path where the PDF report should be saved.

    .PARAMETER SheetName
    Optional. The specific sheet to export (if EntireWorkbook is not used). Defaults to 'Sheet1'.

    .PARAMETER EntireWorkbook
    Optional switch. If specified, exports all sheets in the workbook into a single PDF.

    .EXAMPLE
    Invoke-ExcelExportPDF -FilePath "C:\Report.xlsx" -PdfPath "C:\Report.pdf" -EntireWorkbook
    Exports the entire Excel file to a PDF.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$FilePath, 
        [Parameter(Mandatory = $true)][string]$PdfPath, 
        [string]$SheetName = "Sheet1",
        [switch]$EntireWorkbook
    )
    Write-ToolLine "Excel" "Exporting PDF" $PdfPath
    
    $excel = $null; $wb = $null; $ws = $null
    try {
        if (-not (Test-Path $FilePath)) { throw "File not found." }
        $excel = New-Object -ComObject Excel.Application
        $excel.Visible = $false
        
        $wb = $excel.Workbooks.Open($FilePath)
        
        if ($EntireWorkbook) {
            foreach ($sheet in $wb.Sheets) {
                $sheet.PageSetup.Zoom = $false
                $sheet.PageSetup.FitToPagesWide = 1
                $sheet.PageSetup.Orientation = 2 # Landscape
            }
            # 0 = xlTypePDF
            $wb.ExportAsFixedFormat(0, $PdfPath)
        }
        else {
            $ws = try { $wb.Sheets.Item($SheetName) } catch { $wb.ActiveSheet }
            $ws.PageSetup.Zoom = $false
            $ws.PageSetup.FitToPagesWide = 1
            $ws.PageSetup.FitToPagesTall = $false
            $ws.PageSetup.Orientation = 2 # Landscape
            
            $ws.ExportAsFixedFormat(0, $PdfPath)
        }
        
        Write-StatusLine "OK" "Exported to $PdfPath"
        return "Successfully generated PDF report at $PdfPath"
    }
    catch {
        return "ERROR: $_"
    }
    finally {
        if ($ws) { Dispose-ComObject $ws }
        if ($wb) { $wb.Close($false); Dispose-ComObject $wb }
        if ($excel) { $excel.Quit(); Dispose-ComObject $excel }
        [System.GC]::Collect(); [System.GC]::WaitForPendingFinalizers()
    }
}