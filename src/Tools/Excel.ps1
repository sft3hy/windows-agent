function Invoke-ExcelReadFile {
    <#
    .SYNOPSIS
    Reads data from an Excel file and returns it as a formatted string.

    .DESCRIPTION
    Opens an Excel workbook in read-only mode and extracts the used range as tab-separated values. Useful for quickly reading data into memory or passing to an LLM.

    .PARAMETER FilePath
    The absolute path to the Excel file.

    .PARAMETER SheetName
    Optional. The name of the sheet to read. Defaults to the active sheet.

    .PARAMETER MaxRows
    Optional. The maximum number of rows to read. Default is 100 to prevent memory exhaustion on massive sheets.

    .EXAMPLE
    Invoke-ExcelReadFile -FilePath "C:\Data.xlsx" -MaxRows 50
    Reads the first 50 rows of the active sheet.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$FilePath,
        [string]$SheetName = "",
        [int]$MaxRows = 100
    )
    Write-ToolLine "Excel" "Reading File" $FilePath
    $excel = $null; $wb = $null; $ws = $null
    try {
        if (-not (Test-Path $FilePath)) { throw "File not found: $FilePath" }
        $excel = New-Object -ComObject Excel.Application
        $excel.Visible = $false
        $wb = $excel.Workbooks.Open($FilePath, $null, $true) # Read-only
        $ws = if ([string]::IsNullOrWhiteSpace($SheetName)) { $wb.ActiveSheet } else { $wb.Sheets.Item($SheetName) }
        
        $used = $ws.UsedRange
        $rowCount = [Math]::Min($used.Rows.Count, $MaxRows)
        $colCount = $used.Columns.Count
        
        $output = New-Object System.Text.StringBuilder
        for ($r = 1; $r -le $rowCount; $r++) {
            $line = @()
            for ($c = 1; $c -le $colCount; $c++) {
                $val = $ws.Cells.Item($r, $c).Text
                if ($val -match '[\t\n\r]') { $val = "'$($val -replace "[\t\n\r]", " ")'" }
                $line += $val
            }
            [void]$output.AppendLine(($line -join "`t"))
        }
        
        Write-StatusLine "OK" "Read $rowCount rows"
        return $output.ToString()
    }
    catch {
        return "ERROR: $_"
    }
    finally {
        if ($ws) { Dispose-ComObject $ws }
        if ($wb) { $wb.Close($false); Dispose-ComObject $wb }
        if ($excel) { $excel.Quit(); Dispose-ComObject $excel }
        [System.GC]::Collect(); [System.GC]::WaitForPendingFinalizers()
    }
}

function Invoke-ExcelCreateFile {
    <#
    .SYNOPSIS
    Creates a new Excel file from a TSV/CSV data string.

    .DESCRIPTION
    Takes raw tab-separated or comma-separated string data (often generated by an LLM) and writes it into a brand new Excel workbook, saving it to the specified path.

    .PARAMETER FilePath
    The absolute path where the new Excel file should be saved.

    .PARAMETER Data
    The raw text data containing rows separated by newlines, and columns separated by tabs or commas.

    .PARAMETER SheetName
    Optional. The name to give the worksheet. Defaults to 'Sheet1'.

    .EXAMPLE
    Invoke-ExcelCreateFile -FilePath "C:\Output.xlsx" -Data "Name`tAge`nAlice`t30"
    Creates an Excel file with two columns and two rows.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$FilePath,
        [Parameter(Mandatory = $true)][string]$Data,
        [string]$SheetName = "Sheet1"
    )
    Write-ToolLine "Excel" "Creating File" $FilePath
    $excel = $null; $wb = $null; $ws = $null
    try {
        $excel = New-Object -ComObject Excel.Application
        $excel.Visible = $false
        $excel.DisplayAlerts = $false
        $wb = $excel.Workbooks.Add()
        $ws = $wb.ActiveSheet
        $ws.Name = $SheetName
        
        $rows = $Data -split "\r?\n"
        for ($r = 1; $r -le $rows.Count; $r++) {
            if ([string]::IsNullOrWhiteSpace($rows[$r-1])) { continue }
            $cols = $rows[$r-1] -split "\t"
            if ($cols.Count -eq 1 -and $cols[0] -match ",") { $cols = $rows[$r-1] -split "," }
            
            for ($c = 1; $c -le $cols.Count; $c++) {
                $ws.Cells.Item($r, $c).Value2 = $cols[$c-1]
            }
        }
        
        # Ensure directory exists
        $dir = [System.IO.Path]::GetDirectoryName($FilePath)
        if ($dir -and -not (Test-Path $dir)) { New-Item -Path $dir -ItemType Directory | Out-Null }
        
        $wb.SaveAs($FilePath)
        Write-StatusLine "OK" "Created $FilePath"
        return "Successfully created Excel file at $FilePath"
    }
    catch {
        return "ERROR: $_"
    }
    finally {
        if ($ws) { Dispose-ComObject $ws }
        if ($wb) { $wb.Close(); Dispose-ComObject $wb }
        if ($excel) { $excel.Quit(); Dispose-ComObject $excel }
        [System.GC]::Collect(); [System.GC]::WaitForPendingFinalizers()
    }
}

